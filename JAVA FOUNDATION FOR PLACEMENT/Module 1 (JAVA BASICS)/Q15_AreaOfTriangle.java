public class Q15_AreaOfTriangle {
  public static void main(String[] args) {
    double base = 10;
    double height = 8;
    double area = 0.5 * base * height;
    System.out.println("Base                : " + base);
    System.out.println("Height              : " + height);
    System.out.println("Area of Triangle is : " + area);
  }

}
