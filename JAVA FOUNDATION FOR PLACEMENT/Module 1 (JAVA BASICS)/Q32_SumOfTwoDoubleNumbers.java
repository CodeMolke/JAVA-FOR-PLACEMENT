public class Q32_SumOfTwoDoubleNumbers {
  public static void main(String[] args) {
    double num1 = 10.5;
    double num2 = 20.8;
    double sum = num1 + num2;
    System.out.println("First Number  : " + num1);
    System.out.println("Second Number : " + num2);
    System.out.println("Sum           : " + sum);
  }

}
